--  0061 — team_no 컬럼 SELECT 권한 누락 수정 (0058 회귀)
--
--  ※ 9/26 운영 중 긴급 적용분이라 0059·0060 보다 먼저 DB 에 반영됐다.
--    번호가 뒤인 것은 파일 충돌(0059 가 둘이 되는 것)을 피하려는 것뿐이고,
--    다른 마이그레이션과 순서 의존은 없다.
--
--  0025 가 teams 의 테이블 단위 SELECT 를 회수하고 안전한 컬럼만 하나씩
--  부여했다. 0058 이 team_no 컬럼을 새로 만들면서 이 권한 부여를 빠뜨려,
--  참가자·심사위원 화면(anon/authenticated 키)에서 team_no 를 읽는 쿼리가
--  전부 42501 permission denied 로 실패한다. PostgREST 는 조인 하나가
--  막히면 쿼리 전체를 실패시키므로 증상이 "빈 화면 / 404" 로 나타난다:
--
--    /gallery          → "아직 제출된 작품이 없습니다" (제출물이 있어도)
--    /gallery/[id]     → 404
--    /vote /judge /judge/mid /team /mypage → 목록·팀 정보 없음
--
--  제출물이 0건인 동안에는 갤러리가 어차피 비어 보여서 드러나지 않는다.
--  첫 제출이 들어오는 순간 터지므로 대회 전에 반드시 적용할 것.
--
--  조 번호는 인쇄물·좌석표에 이미 공개된 값이라 숨길 이유가 없다.
--  (0041 이 thumbnail_url 에 했던 것과 같은 후속 조치)
-- =============================================================

grant select (team_no) on teams to anon, authenticated;
