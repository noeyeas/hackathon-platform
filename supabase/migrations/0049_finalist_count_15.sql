-- =============================================================
--  0049 — 1차 선정(전시 진출) 팀 수를 4팀 → 15팀으로 늘린다
--
--  기획 변경: 최종발표 후 상위 4팀만 전시하던 것을 상위 10~15팀으로
--  넓혔다(홈 안내 문구도 이미 "상위 10~15팀"). 운영진이 당일 상황에
--  따라 10~15 사이에서 조정할 수 있도록 상한인 15 를 기본값으로 둔다.
--
--  시상은 그대로 4팀이다 — 전시 진출팀 대상 주민투표 1위가 대상,
--  2~4위가 우수상. rankings 뷰는 finalist_count 만 참조하므로 뷰는
--  손대지 않는다(0045 정의 유지).
-- =============================================================

alter table event_settings
  alter column finalist_count set default 15;

-- 아직 기존 기본값(4)을 그대로 쓰는 행만 올린다. 운영진이 이미 다른
-- 값으로 조정했다면 그 의도를 덮어쓰지 않는다.
update event_settings
   set finalist_count = 15
 where finalist_count = 4;
