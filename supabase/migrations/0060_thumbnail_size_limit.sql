--  0060 — 예시 이미지 업로드 한도 5MB → 4MB
--
--  0041 은 버킷과 앱 모두 5MB 로 잡았지만, 배포처인 Vercel Functions 의
--  요청 본문 상한 4.5MB 가 플랫폼에서 강제된다. next.config 의
--  bodySizeLimit 을 6mb 로 올려 둬도 소용이 없다 — 4.5MB 를 넘는 요청은
--  서버 액션이 실행되기도 전에 413 으로 끊기므로, 앱의 "5MB 이하" 검증은
--  도달조차 하지 않는다. 안내만 5MB 이고 실제로는 올라가지 않는 상태였다.
--
--  파일 한도를 4MB 로 낮춰 나머지 폼 필드와 multipart 오버헤드 몫을
--  남긴다. 앱 쪽 값은 src/lib/upload.ts 의 MAX_IMAGE_BYTES 와 같아야 한다.
--
--  이미 올라간 4MB 초과 파일은 그대로 둔다 — file_size_limit 은 새 업로드
--  에만 적용되고, 기존 객체를 지우지 않는다.
-- =============================================================

update storage.buckets
   set file_size_limit = 4194304   -- 4 * 1024 * 1024
 where id = 'thumbnails';
