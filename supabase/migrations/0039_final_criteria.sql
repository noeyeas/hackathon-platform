-- =============================================================
--  0039 — 심사 기준을 기획(안) 최종 심사 기준표로 교체
--          (제53대 총학생회 26-060호, II-☐심사 기준 및 위원, 나.)
--
--  ⚠ 파괴적: criteria 를 지우면 judge_scores 와 team_scores 가
--    FK on delete cascade 로 함께 지워진다(0001, 0013). 기존 채점이
--    남아 있다면 먼저 백업할 것. 본선 전에 실행하는 것을 전제로 한다.
--
--  배점을 max_score 에 넣는 이유:
--    rankings 뷰(0023)는 criteria.weight 를 쓰지 않는다. 점수를
--    sum(score) / sum(max_score) * 100 으로 정규화하므로 실제 가중치는
--    max_score 가 결정한다. 배점 합이 100 이라 그대로 넣으면
--    judge_100 이 곧 100점 만점 총점이 된다.
--
--  weight 는 채점 화면과 결과 화면에서 "%" 로 보여주는 표시 전용 값이다.
--  배점 합이 100 이므로 배점과 같은 값을 넣으면 표시와 계산이 어긋나지 않는다.
-- =============================================================

delete from criteria;

insert into criteria (name, max_score, weight, sort, description) values
  ('실현 & 상용화 가능성', 30, 30, 1, '실제 지역사회 적용 및 지속 운영 가능 여부 (최대 배점)'),
  ('지역 문제 적합성',     20, 20, 2, '월계1동 실제 주민 수요 및 문제 해결 적합도'),
  ('구현 완성도 & 기술력', 20, 20, 3, '실제 시연 동작 완성도, 코드 및 GitHub 관리 상태'),
  ('창의성 & 차별성',      20, 20, 4, '아이디어의 독창성 및 기존 서비스 대비 차별점'),
  ('발표',                10, 10, 5, '팀당 5분 발표 시간 엄수 (초과 시 감점)');

-- 종합 점수 배분: 심사위원 50% / 팀 상호평가 25% / 주민투표 25%
-- 기획(안)은 "심사 및 주민투표 결과를 반영"이라고만 적고 비율을 정하지 않았다.
-- 팀 상호평가 유지는 운영진 결정 사항이다.
update event_settings
   set weights = '{"judge":0.5,"team":0.25,"audience":0.25}'::jsonb
 where id = 1;
