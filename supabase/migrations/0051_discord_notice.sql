--
--  운영진이 참가자에게 배포한 디스코드 공지가 포스터(0043)보다 구체적이고
--  최신이므로 공지를 기준으로 맞춘다.
--
--  1. 일정
--     · 개회식·OT   18:00 → 18:30, 장소 참빛관 B107호 (0043 이 일괄
--                   '80주년기념관 2층'으로 덮어써 틀려 있었다)
--     · 중간발표    18:00 → 18:30, 장소 80주년기념관 310호.
--                   공지 표기가 '중간발표'라 라벨도 맞춘다
--     · 본선 종료   10.9 13:10 → 15:00경
--     · 전시        장소 80주년기념관 2층
--     장소는 '광운대학교' 접두어 없이 건물명으로 시작하게 적는다 — 홈이
--     place 의 첫 어절을 건물로 세어 대표 장소를 고르기 때문이다.
--
--  2. 심사 기준
--     · 발표 10 → 5점. 남은 5점은 '참여도'(개회식·최종발표 불참 시 인당
--       1점 감점)인데, 심사위원이 매기는 점수가 아니라 운영진이 출석으로
--       별도 반영하므로 criteria 에는 넣지 않는다. 채점표 합은 95점이
--       되고 rankings 뷰는 sum(score)/sum(max_score) 로 정규화하므로
--       계산은 그대로 맞는다(0039).
--     0039 처럼 delete 하지 않고 update 만 한다 — 기존 채점이 cascade 로
--     지워지지 않게.
-- =============================================================

update milestones
   set target_at = timestamptz '2026-09-16 18:30:00+09',
       place     = '참빛관 B107호'
 where label = '개회식';

update milestones
   set label     = '예선 (중간발표 · 멘토링)',
       target_at = timestamptz '2026-09-28 18:30:00+09',
       place     = '80주년기념관 310호'
 where label = '예선 (중간보고 · 멘토링)';

update milestones
   set ends_at = timestamptz '2026-10-09 15:00:00+09',
       place   = '80주년기념관 2~3층'
 where label = '본선 (무박 2일)';

update milestones
   set place = '80주년기념관 2층'
 where label = '전시회';

update criteria
   set max_score   = 5,
       weight      = 5,
       description = '프로젝트 목적·주요 내용·구현 결과·기대효과를 명확하고 효과적으로 전달하는지'
 where name = '발표';
