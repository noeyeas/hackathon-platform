-- =============================================================
--  0048 — 같은 기기로 투표권 여러 장 쓰는 것을 막는다
--
--  0045 의 단위는 "사람"이 아니라 "투표권 한 장"이다. 그래서 한 사람이
--  종이 투표권을 두 장 집어가면 6표가 된다 — 종이 스티커도 같은 약점이
--  있었지만, QR 은 각자 폰으로 흩어져 찍으니 나눠주는 사람의 눈이 닿지 않는다.
--
--  투표한 기기에 표시를 남기고(쿠키), 그 표시를 투표권에 함께 적어 둔다.
--  이미 투표한 기기가 다른 투표권을 찍으면 거절한다.
--
--  이걸로 전부 막히지는 않는다 — 시크릿창이나 폰 두 대면 우회된다.
--  목표는 "지나가다 두 장 집어가는" 가벼운 중복을 걷어내는 것이고,
--  작정한 조작은 배부 통제(1인 1장)와 아래 집계로 드러내는 쪽에 맡긴다.
-- =============================================================

-- 기기 식별자. 쿠키에 담긴 무작위 값이라 개인을 가리키지 않는다
-- (IP 를 쓰지 않는 이유: 전시장 와이파이는 모두가 같은 IP 라 정상 투표까지 막힌다).
alter table audience_ballots
  add column if not exists device_id text;

-- "이 기기가 이미 투표했는가" 를 매 투표마다 조회한다.
create index if not exists audience_ballots_device_idx
  on audience_ballots (device_id)
  where device_id is not null;

-- ---------- 예외 투표권 ----------
-- 기기 차단은 오탐이 난다. 전시장에서는 한 폰으로 어르신 몫까지 대신 찍어
-- 드리는 일이 흔한데, 그때마다 "이미 투표하셨습니다"로 돌려보내면 정작
-- 막아야 할 사람이 아니라 정상 투표자를 잃는다.
--
-- 그래서 안내데스크가 확인하고 내주는 예외 투표권을 따로 둔다. 이 장은
-- 기기 표시를 보지 않는다. 발급 단위로만 열리므로 전체 방어선은 그대로다.
alter table audience_ballots
  add column if not exists allow_shared_device boolean not null default false;
